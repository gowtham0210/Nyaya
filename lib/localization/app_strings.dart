const _codes = ['en', 'hi', 'ta', 'te', 'kn'];

/// Looks up [key] in [_strings] for the language currently selected in
/// [AppLanguage.current] and returns the English fallback if either the key
/// or that language's entry is missing. Static UI copy only — real backend
/// content (article text, quiz questions, leaderboard names, legal-update
/// bodies) is stored in one language server-side and is not machine
/// re-translated here, so it stays as the backend returns it.
String tr(String key) {
  final entry = _strings[key];
  if (entry == null) return key;
  final index = _codes.indexOf(AppLanguage.current.value);
  if (index < 0 || index >= entry.length) return entry[0];
  final value = entry[index];
  return value.isEmpty ? entry[0] : value;
}

